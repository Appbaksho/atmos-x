#!/usr/bin/env python3
"""Write a production .env for docker-compose.prod.yml from a development .env.

    python3 deploy/make-prod-env.py SOURCE_ENV OUT_ENV [EXISTING_PROD_ENV]

Keeps the third-party keys from SOURCE_ENV, drops what the compose file sets itself or what V1 must
never use, and sets the production values below. JWT_SECRET and POSTGRES_PASSWORD are generated
once; when EXISTING_PROD_ENV already has them they are kept, so redeploys don't log everyone out or
lock the API out of its database. Prints key names only, never values.
"""

import os
import secrets
import sys

ORIGIN = "https://atmosx.baksho.app"

# Set by docker-compose.prod.yml, or not allowed in V1 (no language model at runtime).
DROP = {"DATABASE_URL", "DATA_DIR", "API_ORIGIN", "ATMOS_BUILD_ID", "POSTGRES_PORT", "WEB_PORT"}
DROP_PREFIXES = ("OPENAI_", "AI_")

OVERRIDES = {
    "APP_ENV": "production",
    "LOG_LEVEL": "INFO",
    "COOKIE_SECURE": "true",
    "PUBLIC_WEB_ORIGIN": ORIGIN,
    "NEXT_PUBLIC_APP_URL": ORIGIN,
    "DATA_MODE": "live",
    "OSM_USER_AGENT": f'"AtmosX/1.0 (+{ORIGIN})"',
    # Production refuses the console SMS provider; with no Twilio keys, phone sign-in stays off.
    "SMS_PROVIDER": "twilio",
    "SSLCOMMERZ_SANDBOX": "true",
    "NEXT_PUBLIC_TIME_ZONE": "Asia/Dhaka",
    "POSTGRES_USER": "atmos",
    "POSTGRES_DB": "atmos",
}
GENERATED = {"JWT_SECRET": lambda: secrets.token_hex(32), "POSTGRES_PASSWORD": lambda: secrets.token_hex(24)}


def parse(path: str) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path or not os.path.exists(path):
        return out
    for raw in open(path, encoding="utf-8"):
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        out[k.strip()] = v.strip()
    return out


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    existing = parse(sys.argv[3]) if len(sys.argv) > 3 else {}
    env = {k: v for k, v in parse(src).items() if k not in DROP and not k.startswith(DROP_PREFIXES)}
    env.update(OVERRIDES)
    for k, make in GENERATED.items():
        env[k] = existing.get(k) or make()
    fd = os.open(dst, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write("# Atmos X production environment (generated by deploy/make-prod-env.py; never commit)\n")
        for k, v in env.items():
            f.write(f"{k}={v}\n")
    kept = "kept" if all(existing.get(k) for k in GENERATED) else "generated"
    print(f"wrote {len(env)} keys; secrets {kept}: {', '.join(GENERATED)}")
    print("keys:", " ".join(sorted(env)))


if __name__ == "__main__":
    main()

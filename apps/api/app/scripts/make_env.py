"""`make env` (prompt-v1 §8.5): copy ONLY the web variables from the root .env into apps/web/.env.local.

Never prints values. An existing .env.local holding other keys is moved to .env.local.v0.bak first.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
WEB_KEYS = re.compile(r"^(API_ORIGIN|ATMOS_BUILD_ID|NEXT_PUBLIC_[A-Z0-9_]+)$")
LINE = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")


def parse(p: Path) -> list[tuple[str, str]]:
    out = []
    for line in p.read_text().splitlines():
        m = LINE.match(line)
        if m:
            out.append((m.group(1), m.group(2)))
    return out


def main() -> int:
    root_env = ROOT / ".env"
    if not root_env.exists():
        shutil.copy(ROOT / ".env.example", root_env)
        print("created .env from .env.example (fill it in)")
    web = ROOT / "apps/web/.env.local"
    if web.exists():
        others = [k for k, _ in parse(web) if not WEB_KEYS.match(k)]
        if others:
            bak = web.with_name(".env.local.v0.bak")
            if bak.exists():
                bak = web.with_name(".env.local.v0.bak.1")
            web.rename(bak)
            print(f"moved the old apps/web/.env.local ({len(others)} non-web keys) to {bak.name}")
    pairs = [(k, v) for k, v in parse(root_env) if WEB_KEYS.match(k)]
    body = "# Generated by `make env` from the root .env. Web variables only; edit the root .env instead.\n"
    body += "".join(f"{k}={v}\n" for k, v in pairs)
    web.write_text(body)
    web.chmod(0o600)
    print(f"wrote apps/web/.env.local with {len(pairs)} web variables: {', '.join(k for k, _ in pairs)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

/** Helpers for scripts/snapshot.ts (kept separate so they can be unit-tested). */

/** Snapshot names become file names: only [a-z0-9._-]. */
export function fileNameFor(name: string): string {
  if (!/^[a-z0-9][a-z0-9._-]*$/i.test(name)) throw new Error(`bad snapshot name: ${name}`);
  return `${name}.json`;
}

/** Source of src/server/snapshots/dhaka/index.ts: one static JSON import per snapshot (bundled by Next.js). */
export function renderIndex(names: string[]): string {
  const sorted = [...new Set(names)].sort();
  const imports = sorted.map((n, i) => `import s${i} from './${fileNameFor(n)}';`).join('\n');
  const entries = sorted.map((n, i) => `  '${n}': s${i},`).join('\n');
  return `/* Generated by scripts/snapshot.ts on ${new Date().toISOString().slice(0, 10)} — do not edit by hand. */\n${imports}\n\nexport const SNAPSHOTS: Record<string, unknown> = {\n${entries}\n};\n`;
}
